// Generates src/environments/runtime-config.generated.ts from build environment variables.
// `--out <path relative to the repo root>` writes the config to another file instead (e.g. the
// Auth E2E suite's config), leaving the default file untouched.
// Workers Builds shares one variable set across branches, so the Supabase target is chosen
// from WORKERS_CI_BRANCH: only `master` gets the prod project, everything else gets staging.
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const defaultOutFile = resolve(root, 'src/environments/runtime-config.generated.ts');
const PRODUCTION_BRANCH = 'master';

function fail(message) {
  console.error(`[runtime-config] ${message}`);
  process.exit(1);
}

function writeConfig(file, config) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(
    file,
    `// Generated by scripts/generate-runtime-config.mjs. Do not edit or commit.\n` +
      `import type { RuntimeConfig } from '../app/core/config/runtime-config';\n\n` +
      `export const runtimeConfig: RuntimeConfig = ${JSON.stringify(config, null, 2)};\n`,
  );
}

const outIndex = process.argv.indexOf('--out');
let outFile = defaultOutFile;
if (outIndex !== -1) {
  const outArg = process.argv[outIndex + 1];
  if (!outArg || outArg.startsWith('--')) {
    fail('--out requires a path relative to the repository root.');
  }
  outFile = resolve(root, outArg);
}

const envFile = resolve(root, '.env');
if (existsSync(envFile)) {
  process.loadEnvFile(envFile);
}

const env = process.env;
const dataBackend = (env.DATA_BACKEND ?? 'local').trim() || 'local';
if (dataBackend !== 'local' && dataBackend !== 'supabase') {
  fail(`DATA_BACKEND must be "local" or "supabase", got "${dataBackend}".`);
}

const branch = env.WORKERS_CI_BRANCH?.trim();
const target = branch === PRODUCTION_BRANCH ? 'PROD' : 'STAGING';
const supabaseUrl = env[`SUPABASE_URL_${target}`]?.trim() ?? '';
const supabasePublishableKey = env[`SUPABASE_PUBLISHABLE_KEY_${target}`]?.trim() ?? '';

if (supabasePublishableKey && !supabasePublishableKey.startsWith('sb_publishable_')) {
  fail(
    `SUPABASE_PUBLISHABLE_KEY_${target} must be a publishable key (sb_publishable_...). Never use a secret or service_role key in the client.`,
  );
}

if (supabaseUrl) {
  let parsed;
  try {
    parsed = new URL(supabaseUrl);
  } catch {
    fail(`SUPABASE_URL_${target} is not a valid URL.`);
  }
  const isLocalHost = parsed.hostname === '127.0.0.1' || parsed.hostname === 'localhost';
  if (parsed.protocol !== 'https:' && !(isLocalHost && target === 'STAGING' && !branch)) {
    fail(
      `SUPABASE_URL_${target} must use https (http is allowed only for a local stack in local builds).`,
    );
  }
}

if (dataBackend === 'supabase' && (!supabaseUrl || !supabasePublishableKey)) {
  fail(
    `DATA_BACKEND=supabase requires SUPABASE_URL_${target} and SUPABASE_PUBLISHABLE_KEY_${target}.`,
  );
}

const config = {
  dataBackend,
  supabaseTarget: target.toLowerCase(),
  supabaseUrl,
  supabasePublishableKey,
};

writeConfig(outFile, config);

// runtime-config.ts imports the default file, so it must exist even when only --out is generated.
if (outFile !== defaultOutFile && !existsSync(defaultOutFile)) {
  writeConfig(defaultOutFile, {
    dataBackend: 'local',
    supabaseTarget: 'staging',
    supabaseUrl: '',
    supabasePublishableKey: '',
  });
}

console.log(
  `[runtime-config] ${outFile === defaultOutFile ? '' : `out=${relative(root, outFile)}, `}DATA_BACKEND=${dataBackend}, target=${config.supabaseTarget}` +
    `${branch ? ` (branch ${branch})` : ' (local build)'}, supabaseUrl=${supabaseUrl || '(none)'}`,
);
